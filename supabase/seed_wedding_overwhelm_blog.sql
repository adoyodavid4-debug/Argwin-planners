  'There''s a particular kind of tiredness that belongs to planning a wedding. It isn''t the work itself — most individual tasks are small. It''s that the list is *always there*. It''s there at eleven at night. It''s there in the shower. It''s there during a work meeting, whispering that you still haven''t sorted the favours.

And every time you sit down and clear a few things, the list gets longer. You book the florist and inherit four new questions. A friend asks what you''re doing about welcome bags and now that''s a thing you''re doing something about. Eventually you start to feel like you''re failing at a project you''re actually working very hard on.

**A note from David**

*I married my long-term partner, Jewel, on the 29th of November last year — so none of this is theory. It''s written by someone who spent most of last year with a list running in his head at midnight, who realised somewhere around month four that we''d quietly taken on three whole projects nobody had asked us for, and who once lost an entire evening to chairs. What follows is what I wish somebody had told us at the beginning.*

So here''s the reframe that helps most: **a wedding checklist is infinite by design.** There is no natural end to it. An entire industry, several centuries of tradition and everyone you''ve ever met are all contributing items, and none of them are responsible for finishing it. Left alone it will expand to fill every evening you have between now and the day.

Which means the skill you need isn''t working through it faster. It''s closing the scope.

## 1. Decide what kind of wedding this is — in three words

Before another decision gets made, you and your partner need one sentence that settles what this day is actually for. Not a theme. A test.

Sit down together for an hour, and each write down what you want people to feel, what you''ll remember in ten years, and what you honestly don''t care about at all. Then boil it down to three words and write them at the front of the planner.

> *"Relaxed. Loud. Everyone fed."*

Or: intimate, outdoors, no speeches. Or: traditional, elegant, over by ten. Yours will be different — the point is that it''s short enough to remember mid-argument.

From then on, every new item gets one question: **does this serve the three words?** If it doesn''t, it''s not a task you''re behind on — it''s a task that isn''t yours. Chair covers don''t serve "relaxed, loud, everyone fed". Neither do welcome bags. A second round of food at eleven at night absolutely does.

This sounds almost too simple to work. In practice it''s the only thing that reliably stops the list growing, because it gives you a reason to say no that isn''t "I''m too tired" — and it''s a reason you both agreed to in advance, calmly, which matters when one of you is wavering at midnight.

> You''re not behind on the list. The list was never finishable. It was only ever meant to be closed.

## 2. Split decisions from tasks — they''re different work

Here''s why wedding planning feels so much heavier than the hours it takes. A typical list mixes two completely different kinds of work, and treats them as one:

- **Decisions** *(needs both of you, awake)* — choosing the menu. Agreeing the guest list. Deciding who speaks. Settling what you''ll spend on flowers. Heavy, occasionally emotional, and impossible to do well at 11pm on a Wednesday.
- **Tasks** *(needs ten minutes and a phone)* — emailing final numbers. Chasing an RSVP. Paying a deposit. Confirming arrival times. Light, boring, and completely doable in a lunch break by one person alone.

Keep them on separate pages. Most of the exhaustion comes from looking at a single list where "pick our first dance" sits next to "email Rachel the parking details" — so the whole thing feels enormous, and you do neither.

Once they''re split, the tasks stop being scary — they''re errands, and you can clear six of them standing in a queue. And the decisions get the thing they actually need: both of you, in a decent mood, with a defined amount of time.

## 3. Give it one hour a week, with an agenda

This is the change that gets the wedding out of the rest of your life. Not less planning — *contained* planning.

One fixed appointment a week, both of you, same day and time, forty-five minutes to an hour. In the diary like anything else. Everything that isn''t urgent waits for it. And critically: **outside that hour, wedding talk is off.**

| Time | Item | What happens |
| --- | --- | --- |
| 5 min | **What got done** | Read it out. You''ve done more than you think, and starting here changes the tone of the hour. |
| 10 min | **Anything urgent** | Deadlines this week, suppliers waiting on an answer, deposits due. Only genuine time pressure. |
| 20 min | **This week''s decisions** | Two or three, chosen last week so you both had time to think. Decide them and write them down as settled. |
| 10 min | **Assign the tasks** | Who does what before next week. Names against items, or they don''t happen. |
| 5 min | **Pick next week''s decisions** | So neither of you is ambushed. Then close the folder. |

The banned-outside-the-hour rule is the part people resist and later say saved them. Without it, every meal and car journey for a year becomes a planning meeting, and you slowly stop having a relationship that isn''t logistics. With it, an idea at 11pm goes into the notes app and waits — and half of those ideas turn out not to matter by Sunday, which is useful information in itself.

## 4. Work backwards, and use the latest safe date

Wedding timelines published by suppliers are designed to get you to book early. That''s not a conspiracy — it''s just their interests, not yours. The effect is that everything feels urgent from month one, so you spend a year at maximum stress.

Plan it the other way. Work back from the date and give every item the **latest date it could safely happen**, then schedule it there. The list stops screaming all at once, and you get to have a normal spring.

| Out from the day | What happens |
| --- | --- |
| 12 months | **Date, venue, rough numbers.** Genuinely early, because venues and dates are the one real constraint. Almost nothing else is. |
| 9 months | **The book-out suppliers.** Photographer, caterer, band or DJ — the ones who take one booking per day and no more. |
| 6 months | **Outfits and invitations.** Both have long lead times. Everything else can still wait, whatever the internet says. |
| 3 months | **Invitations out, menu, cake.** Send them too early and people forget; too late and they''ve booked something else. |
| 6 weeks | **Chase RSVPs, start seating.** Impossible earlier, because people don''t reply until they must. Not a thing to feel behind on. |
| 3 weeks | **Final numbers and the run sheet.** One page: who''s where, when, with what phone number. Sent to every supplier. |
| 2 weeks | **The freeze — nothing new.** No new ideas, no "wouldn''t it be lovely if". From here you only finish what''s started. |
| The week | **Hand it over.** Someone else runs the day. Your job is to show up and get married. |

Look at what this means: most of the list *cannot* be done early even if you want to. So the guilt you''re feeling in month three is about work that isn''t possible yet.

## 5. Capture the 11pm ideas — don''t act on them

Ideas don''t arrive politely during your planning hour. They arrive in bed, at work, and immediately after seeing someone else''s wedding photos.

So keep one page called **Maybe** and put every one of them there. Not the main list — the main list is closed. Just Maybe.

Then read that page once a month, in the planning hour, and test each item against the three words. Most will be quietly dropped without ever costing you an evening. The few that survive get added deliberately, with a date and an owner, as a genuine decision rather than a 1am impulse. Capturing an idea and committing to it are completely different acts, and keeping them separate is most of the battle.

## 6. Delegate whole categories, not tasks

People will offer to help. Most couples answer with small tasks, which is the worst possible use of the offer — because now you''re managing them, and managing someone is more work than doing it.

Hand over a **whole category** instead, with three things attached: the budget, the deadline, and the authority to make the final call without checking back. "You own the cake. Here''s what we can spend, here''s when it''s needed, and we''ll like whatever you choose." Then don''t revisit it.

Yes, it will be slightly different from what you''d have picked. That''s the trade, and on the day nobody — including you — will be able to tell which choices were yours. What you buy with that is an entire category permanently off the list.

## 7. Handle the opinions, one rule at a time

A surprising amount of the list arrives from other people. Relatives with traditions, friends with expectations, someone who firmly believes there must be a receiving line.

Two things make this manageable. First, agree that **every item has exactly one decision-maker** — one of you, or someone you''ve delegated to — and that the two of you are always the final word on your own day. Second, keep one phrase ready for the moment, because arguing in the kitchen never goes well:

> *"That''s a lovely idea — let me add it to the list and we''ll look at it properly this weekend."*

It''s true, it''s warm, and it moves the conversation out of the moment and into the Maybe page, where the three-words test can do its work without anyone''s feelings getting hurt.

## 8. Decide in advance what you''re not doing

The last five per cent of any wedding list never gets done. That''s not a prediction about you; it''s simply what happens, every time, to everybody.

So choose which five per cent it is, while you still have the choice. Write a short page headed **Deliberately not doing** and put things on it: favours. A second outfit change. Handmade place cards for ninety people. A choreographed first dance. The seating chart in calligraphy.

Two things happen. The list gets shorter immediately, and — more importantly — those items stop generating guilt, because they''re now decisions rather than failures. An abandoned task nags. A deliberate omission doesn''t.

## 9. Protect the thing the day is actually about

The most common regret from people a year out isn''t about the flowers. It''s that for eight months they stopped being a couple and became project co-managers, and the whole thing got a bit joyless somewhere around the seating plan.

So put one evening a month in the diary where the wedding is not mentioned. No venue talk, no numbers, no "quick question about the cars". Go out, or stay in and watch something rubbish. It''s the single most protective thing in this entire article, and it takes no planning at all.

And in the final fortnight, when the freeze is on and the list is closed, let it be close. Nobody at your wedding will notice the thing you didn''t get to. What they''ll remember is whether they felt welcome, whether the food was good, whether they could hear, and whether the two of you looked happy. Every single one of those survives an unfinished checklist.

Ours was ten months ago now. I genuinely cannot tell you what we decided about the chairs — the thing that swallowed two entire evenings in month five. What I remember is Jewel laughing halfway through the vows, a speech that ran far too long and was perfect anyway, and the food arriving late to a room full of people who never noticed. The list did not finish. Nobody has ever once mentioned it.

## The one-hour setup

This weekend, before another item gets added:

1. Write your three words together, on the first page of the planner.
2. Split the existing list into two: decisions and tasks. Put them on separate pages.
3. Work backwards from the date and give every item its latest safe date, not its earliest.
4. Book the weekly wedding hour in the diary, recurring, and agree the no-talk-outside-it rule.
5. Start the Maybe page and the Deliberately-not-doing page. Put three things on the second one now.

The list still won''t finish. That was never available. But it''ll be a closed list, on a schedule, living in one hour a week instead of in your head at eleven at night — which is the difference between planning a wedding and being consumed by one.

