What actually happens is slower and much harder to spot from the inside. You skip the gym once because of a deadline — completely reasonable. You eat at your desk, which is fine, it''s one day. You move the same task to next week for the third time. You stop making weekend plans because you''re "too tired to commit to anything". Each decision is sensible in isolation. Six weeks of them stacked together is a different thing entirely, and by the time you feel it, you''ve been living in it for a while.

Here''s the part that makes a planner unexpectedly powerful: **you wrote all of it down.** Not the feelings — the evidence. Dated, in order, in your own hand. Which means you can spot the pattern while it''s still a pattern, rather than after it''s become a problem.

## 1. What burnout actually is (it''s more specific than "tired")

Worth getting this right, because the word gets used for everything from a bad Tuesday to a crisis.

The World Health Organization classifies burn-out in the ICD-11 as an **occupational phenomenon** — specifically not a medical condition — resulting from chronic workplace stress that hasn''t been successfully managed. It''s described in three dimensions:

- **Exhaustion.** Not ordinary tiredness. The kind where a full weekend of rest doesn''t touch it and Monday feels the same as Friday did.
- **Distance.** Cynicism about the work, or a flat numbness toward it. Things that used to matter now produce a shrug.
- **Reduced efficacy.** A sense that you''re not actually good at this any more — usually while doing more hours than ever.

Notice the WHO frames it as job-related. Plenty of exhaustion comes from elsewhere — caring, studying, a rough period — and that''s real too, but it''s a different thing wearing similar clothes.

Notice also that the second and third dimensions aren''t about energy at all. That''s why "I''ll sleep more" so often fails as a fix: you can be sleeping eight hours and still be sliding, because what''s depleted isn''t rest.

## 2. Six signals hiding in your own pages

Open the last two months of your planner and go looking. These are the patterns worth checking, roughly in the order they tend to show up.

1. **The rollover count is climbing.** Count tasks moved forward three or more times. A few is normal. A rising count across six weeks means you''re committing to more than exists — the gap is widening, not closing.
2. **The white space is gone.** Flip through and look at the shape, not the words. Empty patches are where recovery lives. If the last clear evening was five weeks ago, that''s your answer and you didn''t even have to read anything.
3. **The habit rows went quiet.** Not dropped in a dramatic collapse — just tapering. Ticks thinning from daily to a couple a week to nothing, with no decision ever made. Nobody chooses to stop; it gets crowded out.
4. **Everything on the page is work.** Scan for entries that aren''t work or admin. If a whole month contains nothing you did purely because you wanted to, that''s the most reliable signal on this list.
5. **The "done" column shrank while the hours grew.** Long days, less finished. That''s the efficacy dimension showing up as data — and it''s usually the point where people start privately concluding they''ve lost it.
6. **Weekends stopped being planned.** Saturday and Sunday pages going blank, or filling with chores only. Often the earliest signal of all, because it''s the first thing to go and nobody notices it leaving.

None of these is a diagnosis. They''re not a test and there''s no score. They''re patterns in your own behaviour that are easy to miss day by day and obvious across eight weeks — which is exactly the timescale a planner covers and memory doesn''t.

