Here''s the annoying bit: being told about the planning fallacy doesn''t make you immune. People who know it exists still do it. Researchers who *study* it still do it.

The reason is in how you produce the estimate. When you guess how long something takes, your brain doesn''t consult your history — it runs a little film of the task going smoothly. Sit down, focus, do the thing, done. That film is accurate! It''s just a film of the best possible version, and it never includes the bit where your manager sends "quick call?" at 2pm.

So you''re not estimating the task. You''re estimating **the plan**. And the plan has no interruptions in it, because interruptions aren''t part of anyone''s plan. That''s rather the point of them.

**Where the missing time goes:**

- **Startup cost** (5–15 min, every time) — finding the file, remembering where you left off, opening the right tabs. Your estimate started counting from the moment you were already working.
- **The switch tax** — every interruption costs the interruption plus the re-entry. Four "quick questions" can eat an afternoon and leave no trace.
- **The last 10%** — formatting, checking, sending, the small fix you spot at the end. Never in the estimate. Always in the day.
- **Admin gravity** — email, messages, the thing that broke. Not on your list, definitely in your day.

## 3. The fix: plan from history, not from hope

Here''s the thing that actually works, and it''s almost insultingly simple. Instead of asking *"how long will this take?"*, ask:

> "How long did it take **last time**?"

Researchers call this reference class forecasting — using what similar tasks actually cost rather than imagining this one. Everyone else can call it *looking it up*.

The catch is you need a record, which is exactly what most people don''t have. You remember that the report "took a while". You don''t remember it took three hours and forty minutes across two sittings. And without that number, your brain cheerfully supplies "about an hour and a half".

So for two weeks, do this one boring thing: next to each finished task, write **how long it actually took**. Not a time-tracking app. A number in a margin.

Two weeks of that and you''ll have a personal correction factor — the ratio between what you predict and what''s true. Most people''s lands somewhere between 1.5× and 2×. Once you know yours, planning becomes arithmetic instead of optimism.

## 4. Four rules that survive contact with a real week

- **The 1.5× rule.** Estimate honestly, then multiply by your correction factor before it goes in the calendar. If that makes the day look impossible, the day *was* impossible — you just found out on Sunday instead of Thursday.
- **Three things, not nine.** A nine-item day is a wish. Three real items plus whatever else fits is a plan, and it ends with you having done everything you said.
- **Leave a third of the day empty.** Not as slack — as the realistic allocation for the stuff that always happens and never gets planned. Block it as "buffer" so nobody books it.
- **Count in half-days, not hours.** "Thursday morning: the deck" is a commitment you can keep. "2:00–2:45: the deck" is a fantasy with a colon in it.

## 5. Estimate the week too, not just the tasks

The planning fallacy scales up nastily. If every task is 1.7× off, a week with twelve tasks isn''t slightly late — it''s structurally impossible, and you find out on Friday.

So do the arithmetic once, on purpose. Add up your estimates for the week, apply your correction factor, and compare it against the hours you genuinely have after meetings and admin. Almost everyone discovers they''ve committed to roughly double their capacity.

That''s not a character flaw either. It''s the same bug, compounding. But now it''s visible, and a visible problem is one you can cut down on Monday instead of apologising for on Friday.

## 6. The trick that beats everything else

One more, and it''s the strongest in this whole piece: **ask someone else how long they think it''ll take you.**

Observers are dramatically better at predicting your timelines than you are, because they''re not running the film. They''re going on the boring outside evidence — that you''re always a bit late with these, that last time was a scramble, that you''ve got two other things on. They have no ego in the estimate, so they just... guess accurately.

It''s mildly humiliating and extremely effective. If you''ve got a colleague or a partner who knows your work, ask them. Their number will be higher than yours. Their number is the one to use.

## The two-week experiment

1. For two weeks, write the actual time next to every finished task. Just a number in the margin.
2. At the end, work out your ratio: predicted vs actual. That''s your correction factor.
3. From then on, estimate, multiply, *then* commit.
4. Cap the day at three real items and block a third of it as buffer.
5. Once a week, total the estimates against the hours you actually have. Cut until it fits.

You won''t become accurate. Nobody does — the bias is stubborn. But you''ll become accurate *about how inaccurate you are*, which turns out to be just as good.

