- **Schedule it. Never ambush.** "Can we talk about money?" sprung at 10pm on a Tuesday starts a fight. A standing Sunday slot starts an admin task.
- **Numbers first, opinions second.** Read the facts out loud before anyone interprets them. Most money arguments are two people arguing about different versions of the numbers.
- **Separate "what happened" from "what it means".** One is bookkeeping, the other is values. Doing both in the same ten minutes is how you end up discussing someone''s childhood.
