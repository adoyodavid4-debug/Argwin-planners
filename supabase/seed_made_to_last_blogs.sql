## 3. Run the ten-minute audit monthly

Once a month, same slot, ten minutes. Open the last eight weeks and ask four questions. Write the answers down, because the point is to compare them next month.

1. **How many things rolled over three times or more?** One number. Track it monthly and watch the direction.
2. **How many genuinely unplanned evenings did I have?** Free, not just "nothing scheduled while I worked at home".
3. **What did I do purely for enjoyment?** List it. If the list is empty, that''s the finding.
4. **Which week was the worst, and what was different about it?** There''s usually a specific cause, and it''s usually still there.

Four numbers, ten minutes. What makes this work is the comparison — one month''s answers mean very little; three months in a row showing the same drift is a trend you can act on while acting is still cheap.

## 4. What to do when the audit looks bad

Two mistakes here. One is ignoring it. The other — more common among the kind of person who keeps a planner — is responding with a dramatic overhaul: a new system, a 5am routine, seven new habits. That''s just more load, and it fails within a fortnight.

Smaller moves, in this order:

- **Subtract before you add.** Take one real commitment off, this week. Not "do it later" — actually off. Nothing gets better while the total keeps rising.
- **Reclaim one evening and defend it properly.** One, weekly, in the calendar with a name. Recovery needs to be scheduled or it loses to everything else.
- **Restart one habit at its smallest version.** Not all four. The one you miss most, at the floor version — a ten-minute walk, not a return to the gym.
- **Deal with the worst week''s cause.** You identified it in the audit. It''s probably a specific project, person, or recurring commitment. That''s the actual lever, and it usually requires a conversation rather than a planner page.
- **Put one good thing in the diary.** Something to look forward to within the next fortnight. Anticipation does real work, and there''s been nothing worth anticipating for a while.

## 5. Where a planner stops being the right tool

Now the honest part, because a wellness post from a stationery company should have a limit written into it.

Everything above helps with a workload that''s crept up on you — which is most cases, and which a good weekly routine genuinely does fix. But if you run the audit, subtract things, protect the evenings, and months later nothing shifts — or if what you''re feeling is heavier than tiredness and has stopped lifting at weekends or on holiday — then this isn''t a planning problem and no amount of ticking boxes will touch it.

That''s a conversation with a doctor, or a therapist, or whatever support you have access to where you are. It''s not a failure of routine, and it''s not something you should be trying to organise your way out of alone. The audit pages are genuinely useful there, actually — turning up with eight weeks of specifics beats trying to describe a vague feeling from memory.

## The ten-minute audit

1. Open the last eight weeks of your planner. Look at the shape before you read the words.
2. Count the three-times-rolled-over tasks. Write the number down.
3. Count the genuinely free evenings, and list anything you did purely for enjoyment.
4. Find the worst week and name what caused it.
5. Do one subtraction this week. Book the audit again for a month''s time.

